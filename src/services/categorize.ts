import { aiAvailable, apiCategorize } from './api';

/** Словарь v0.1 — офлайн-fallback и мгновенная подсказка при вводе. */
const KEYWORDS: Record<string, string[]> = {
  Покупки: ['купить', 'покупка', 'магазин', 'молоко', 'хлеб', 'продукты', 'заказать', 'доставка', 'озон', 'вб', 'wildberries', 'ашан', 'лента', 'перекр', 'пятёр', 'пятер', 'маркет', 'заказ', 'чек', 'скидк', 'распродаж'],
  Здоровье: ['врач', 'стоматолог', 'анализ', 'таблетк', 'лекарств', 'спорт', 'зарядк', 'зал', 'вода', 'сон', 'медитац', 'бег', 'тренировк', 'здоров', 'зубы', 'витамин', 'диет', 'прививк', 'клиник', 'больниц', 'аптек'],
  'Работа / Деньги': ['работа', 'проект', 'клиент', 'созвон', 'встреч', 'отчёт', 'оплат', 'счёт', 'налог', 'зарплат', 'перевод', 'банк', 'деньги', 'кредит', 'ипотек', 'инвестиц', 'заработ', 'презентац', 'дедлайн', 'задача', 'митинг', 'офис', 'коллег', 'начальник'],
  Развитие: ['книг', 'курс', 'выучить', 'почитать', 'посмотреть', 'youtube', 'урок', 'лекци', 'изучить', 'подкаст', 'английск', 'язык', 'навык', 'научит', 'прочит', 'тренинг', 'вебинар'],
  Семья: ['мама', 'папа', 'жена', 'муж', 'дети', 'сын', 'дочь', 'позвонить', 'подарок', 'день рожден', 'семь', 'родител', 'бабушк', 'дедушк', 'сестр', 'брат', 'свидан', 'отношен', 'любим'],
  'Когда-нибудь': ['мечт', 'хочу', 'когда-нибудь', 'однажды', 'путешеств', 'переехать', 'машин', 'дом', 'страна', 'мир'],
};

export function categorizeByKeywords(text: string, categories: string[]): string {
  const lower = text.toLowerCase();
  for (const cat of categories) {
    for (const word of KEYWORDS[cat] ?? []) {
      if (lower.includes(word)) return cat;
    }
  }
  return categories[categories.length - 1] ?? 'Когда-нибудь';
}

/** LLM-категоризация с fallback на ключевые слова. */
export async function categorize(text: string, categories: string[]): Promise<string> {
  if (aiAvailable()) {
    const cat = await apiCategorize(text, categories);
    if (cat) return cat;
  }
  return categorizeByKeywords(text, categories);
}
